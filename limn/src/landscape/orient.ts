import { fitRigid } from '../mol/superpose'
import type { Molecule } from '../mol/types'

/** 本地服务给出的 OPM 取向数据 / OPM orientation data as the local service returns it */
export interface OpmData {
  pdbId: string
  half: number
  keys: string[]
  xyz: number[]
}

/** 一个结构在膜坐标系里的摆法 / how a structure sits in the membrane frame */
export interface MembraneFit {
  /**
   * 列主序 4x4：把结构自己的坐标变到膜坐标系（法线沿 z，膜正中在 z = 0，z 为正是外侧）。
   * Column-major 4x4 taking the structure's own coordinates into the membrane frame (normal
   * along z, mid-membrane at z = 0, positive z outside).
   */
  matrix: Float32Array
  /** 疏水层半厚度（Å）/ half-thickness of the hydrophobic slab, Å */
  half: number
  matched: number
  rmsd: number
}

/**
 * 把结构叠合到 OPM 给的 Cα 位置上，按作者链名和残基号配对。两者本是同一套坐标，只差一个刚体运动，
 * 所以配上的残基应当几乎完全重合；偏差大说明链名对不上（常见于由对称操作生成的组装体），这时返回 null。
 *
 * Superpose a structure onto OPM's Cα positions, pairing by author chain id and residue number.
 * The two are the same coordinates up to one rigid motion, so paired residues should coincide
 * almost exactly; a large deviation means the chain names do not correspond (common when the
 * assembly was generated by symmetry), and null is returned.
 */
export function fitToMembrane(mol: Molecule, opm: OpmData): MembraneFit | null {
  const target = new Map<string, number>()
  opm.keys.forEach((k, i) => target.set(k, i))
  const from: number[] = [], to: number[] = []
  for (const ch of mol.chains) {
    if (mol.entities[ch.entity]!.kind !== 'protein') continue
    for (let i = ch.start; i < ch.start + ch.count; i++) {
      if (!mol.isTrace[i]) continue
      const j = target.get(`${ch.authAsymId}:${mol.authResidue ? mol.authResidue[i] : mol.residue[i]}`)
      if (j === undefined) continue
      from.push(mol.pos[i * 3]!, mol.pos[i * 3 + 1]!, mol.pos[i * 3 + 2]!)
      to.push(opm.xyz[j * 3]!, opm.xyz[j * 3 + 1]!, opm.xyz[j * 3 + 2]!)
      target.delete(`${ch.authAsymId}:${mol.authResidue ? mol.authResidue[i] : mol.residue[i]}`)
    }
  }
  const matched = from.length / 3
  if (matched < 20) return null
  const fit = fitRigid(from, to)
  if (fit.rmsd > 1.5) return null
  return { matrix: fit.matrix, half: opm.half, matched, rmsd: fit.rmsd }
}

/**
 * 膜坐标系到场景坐标系的旋转（列主序 3x3）。场景里膜是水平的，法线沿 y；`outer` 说外侧在上还是在下。
 * The rotation (column-major 3x3) from the membrane frame to the scene. In the scene the
 * membrane is horizontal with its normal along y; `outer` says whether outside is up or down.
 */
export function membraneToScene(outer: 'above' | 'below'): Float32Array {
  // 上：(x, y, z) -> (x, z, -y)；下：(x, y, z) -> (x, -z, y) / up: (x, y, z) -> (x, z, -y); down: (x, y, z) -> (x, -z, y)
  return outer === 'above' ? new Float32Array([1, 0, 0, 0, 0, -1, 0, 1, 0]) : new Float32Array([1, 0, 0, 0, 0, 1, 0, -1, 0])
}
