"""模型的记号序列和每个记号的时长 → 音素时间线。纯函数，不需要模型。
The model's symbol sequence and per-symbol durations → a phoneme timeline. Pure functions; no model needed.

Kokoro 的时长预测器给每个输入记号一个整数帧数（一帧 = 600 个采样 = 25 ms，24 kHz），声音正是按这些帧数展开生成的，
所以时间线是模型内部的对齐，不是事后从声音里猜的。重音记号、声调数字、空格也是记号、也占帧：这里把它们并到相邻的音上。
Kokoro's duration predictor gives every input symbol a whole number of frames (one frame = 600 samples = 25 ms at
24 kHz), and the audio is generated by expanding the symbols by exactly those frames. The timeline is therefore the
model's own alignment, not something guessed from the audio afterwards. Stress marks, tone digits and spaces are
symbols too and take frames; here they are merged into the neighbouring sounds.
"""

from __future__ import annotations

from dataclasses import dataclass, field

FRAME_SECONDS = 0.025
# 位置用半帧的整数表示，这样空格可以对半分 / positions are whole half-frames, so a space can be split in two
HALF = FRAME_SECONDS / 2

PUNCT = frozenset(';:,.!?—…"()“”')
SPACES = frozenset(" /")
STRESS = {"ˈ": 1, "ˌ": 2}

# misaki（美式英语）的记号 → ARPAbet。元音在后面的集合里。ə、ᵊ 记作 AX，ᵻ 记作 IX，闪音 T 记作 DX（扩展 ARPAbet）。
# misaki's symbols (American English) → ARPAbet. The vowels are the set below. ə and ᵊ become AX, ᵻ becomes IX and the
# flap T becomes DX (extended ARPAbet).
EN_SYMBOLS: dict[str, str] = {
    "b": "B", "d": "D", "f": "F", "h": "HH", "j": "Y", "k": "K", "l": "L", "m": "M", "n": "N", "p": "P", "s": "S",
    "t": "T", "v": "V", "w": "W", "z": "Z", "ɡ": "G", "g": "G", "ŋ": "NG", "ɹ": "R", "ʃ": "SH", "ʒ": "ZH", "ð": "DH",
    "θ": "TH", "ʤ": "JH", "ʧ": "CH", "T": "DX", "ɾ": "DX", "ʔ": "T",
    "ə": "AX", "ᵊ": "AX", "i": "IY", "u": "UW", "ɑ": "AA", "ɔ": "AO", "ɛ": "EH", "ɜ": "ER", "ɪ": "IH", "ʊ": "UH",
    "ʌ": "AH", "A": "EY", "I": "AY", "W": "AW", "Y": "OY", "O": "OW", "æ": "AE", "ᵻ": "IX",
    # 英式记号，本服务的声音不会产生，留着以防词典里出现 / British symbols; not produced by this service's voices, kept in case a dictionary entry has one
    "a": "AE", "ɒ": "AA", "Q": "OW", "ɐ": "AX",
}
EN_VOWELS = frozenset({"AX", "IY", "UW", "AA", "AO", "EH", "ER", "IH", "UH", "AH", "EY", "AY", "AW", "OY", "OW", "AE", "IX"})
ARPABET = sorted(set(EN_SYMBOLS.values()))

# 模型（v1.1-zh）的记号 → 拼音的声母和韵母。韵母按 pypinyin 的写法：ü 写作 v，iou / uei / uen 不缩写，
# ii 是 zi ci si 的韵母，iii 是 zhi chi shi ri 的韵母。
# The model's (v1.1-zh) symbols → pinyin initials and finals. Finals are spelled as pypinyin does: ü is written v,
# iou / uei / uen are not abbreviated, ii is the final of zi ci si and iii that of zhi chi shi ri.
ZH_INITIALS: dict[str, str] = {
    "ㄅ": "b", "ㄆ": "p", "ㄇ": "m", "ㄈ": "f", "ㄉ": "d", "ㄊ": "t", "ㄋ": "n", "ㄌ": "l", "ㄍ": "g", "ㄎ": "k", "ㄏ": "h",
    "ㄐ": "j", "ㄑ": "q", "ㄒ": "x", "ㄓ": "zh", "ㄔ": "ch", "ㄕ": "sh", "ㄖ": "r", "ㄗ": "z", "ㄘ": "c", "ㄙ": "s",
}
ZH_FINALS: dict[str, str] = {
    "ㄚ": "a", "ㄛ": "o", "ㄜ": "e", "ㄝ": "ie", "ㄞ": "ai", "ㄟ": "ei", "ㄠ": "ao", "ㄡ": "ou", "ㄢ": "an", "ㄣ": "en",
    "ㄤ": "ang", "ㄥ": "eng", "ㄦ": "er", "ㄧ": "i", "ㄨ": "u", "ㄩ": "v", "ㄭ": "ii", "十": "iii", "月": "ve", "压": "ia",
    "言": "ian", "阳": "iang", "要": "iao", "阴": "in", "应": "ing", "用": "iong", "又": "iou", "中": "ong", "穵": "ua",
    "外": "uai", "万": "uan", "王": "uang", "为": "uei", "文": "uen", "瓮": "ueng", "我": "uo", "元": "van", "云": "vn",
}
ZH_ERHUA = "R"
ZH_TONES = frozenset("12345")


@dataclass
class Unit:
    """一个模型记号：记号本身、帧数、属于第几个词（不属于任何词时为 None）。
    One model symbol: the symbol, its frames, and the index of its word (None when it belongs to no word)."""

    symbol: str
    frames: int
    word: int | None = None


@dataclass
class Seg:
    phone: str
    symbol: str
    start: int  # 半帧 / half-frames
    end: int
    word: int | None = None
    extra: dict = field(default_factory=dict)


def _pause(symbol: str, start: int, end: int) -> Seg:
    return Seg("sil", symbol, start, end, None, {})


def _layout(units: list[Unit], lead: int, trail: int) -> tuple[list[tuple[Unit, int, int]], int]:
    """每个记号的起止（半帧）。lead / trail 是句首和句尾记号的帧数。
    Start and end of every symbol in half-frames. `lead` and `trail` are the frames of the begin and end symbols."""
    at = 2 * lead
    out = []
    for u in units:
        out.append((u, at, at + 2 * u.frames))
        at += 2 * u.frames
    return out, at + 2 * trail


# 声音比名义上的对齐早大约两帧：在 16 个试验句（示范句加四句）上，塞音闭塞处能量骤降的时刻比名义边界早，中位数是 47.5 ms（英语 49 处、
# 普通话 29 处）。所以所有内部边界提前 2 帧（50 ms）。Kokoro 自己给词定时间时，对句首也减了 3 帧。
# The audio runs about two frames ahead of the nominal alignment: on 16 trial sentences (the demo ones and four more) the energy fall at stop
# closures came before the nominal boundary by a median of 47.5 ms (49 places in English, 29 in Mandarin). All inner
# boundaries are therefore moved 2 frames (50 ms) earlier. Kokoro's own word timestamps also subtract 3 frames at the start.
SHIFT_HALF = 4
# 停顿旁边的音至少留这么长 / a sound next to a pause keeps at least this much
MIN_HALF = 4


def align(segs: list[Seg], total: int, audible: list[bool] | None) -> list[Seg]:
    """把名义上的时间线对到声音上：先整体提前 SHIFT_HALF；再用每帧"有没有声音"修正停顿的两头——模型常把句末的静音
    算进最后一个记号里，把句首的第一个音提前到起始记号里。audible 为 None 时只做整体提前。
    Fit the nominal timeline to the audio: first move everything SHIFT_HALF earlier; then use the per-frame "is there
    sound" flags to correct both ends of every pause — the model tends to put the silence at the end of a phrase into
    its last symbol and to start the first sound inside the begin symbol. With `audible` None only the shift is done."""
    for i in range(len(segs) - 1):
        b = max(segs[i].start, segs[i].end - SHIFT_HALF, 0)
        segs[i].end = b
        segs[i + 1].start = b
    segs = [s for s in segs if s.end > s.start]
    if audible is not None:
        frames = len(audible)

        def last_audible(lo: int, hi: int) -> int | None:
            for f in range(min(hi, frames) - 1, lo - 1, -1):
                if audible[f]:
                    return f
            return None

        def first_audible(lo: int, hi: int) -> int | None:
            for f in range(max(lo, 0), min(hi, frames)):
                if audible[f]:
                    return f
            return None

        for i, p in enumerate(segs):
            if p.phone != "sil":
                continue
            a = segs[i - 1] if i > 0 else None
            b = segs[i + 1] if i + 1 < len(segs) else None
            if a is not None:
                f = last_audible(a.start // 2, p.end // 2)
                edge = a.start + MIN_HALF if f is None else max(2 * (f + 1), a.start + MIN_HALF)
                edge = min(edge, p.end)
                a.end = p.start = edge
            if b is not None:
                f = first_audible((p.start + 1) // 2, b.end // 2)
                edge = p.end if f is None else min(2 * f, b.end - MIN_HALF)
                edge = max(edge, p.start)
                p.end = b.start = edge
        segs = [s for s in segs if s.end > s.start]
    return segs


def _finish(segs: list[Seg], total: int, lead: int) -> list[Seg]:
    """补上句首句尾的停顿，把空格的时间分给两边，合并相邻的停顿。
    Add the leading and trailing pauses, hand the time of spaces to their neighbours, and merge adjacent pauses."""
    segs = [_pause("", 0, 2 * lead), *segs]
    last_end = segs[-1].end
    segs.append(_pause("", last_end, total))
    out: list[Seg] = []
    i = 0
    while i < len(segs):
        s = segs[i]
        if s.phone != " ":
            out.append(s)
            i += 1
            continue
        # 连续的空格并在一起处理 / runs of spaces are handled together
        j = i
        while j < len(segs) and segs[j].phone == " ":
            j += 1
        start, end = s.start, segs[j - 1].end
        prev = out[-1] if out else None
        nxt = segs[j] if j < len(segs) else None
        if prev is not None and prev.phone == "sil":
            prev.end = end
        elif nxt is not None and nxt.phone == "sil":
            nxt.start = start
        elif prev is not None and nxt is not None:
            mid = (start + end) // 2
            prev.end = mid
            nxt.start = mid
        elif prev is not None:
            prev.end = end
        elif nxt is not None:
            nxt.start = start
        i = j
    merged: list[Seg] = []
    for s in out:
        if s.end <= s.start:
            continue
        if merged and merged[-1].phone == "sil" and s.phone == "sil":
            merged[-1].end = s.end
            merged[-1].symbol = (merged[-1].symbol + s.symbol)[:8]
        else:
            merged.append(s)
    return merged


def english_segments(units: list[Unit], lead: int, trail: int, audible: list[bool] | None = None) -> list[Seg]:
    """英文：重音记号的时间并入紧跟的音，重音等级记在随后的第一个元音上；ɜɹ 和不在元音前的 əɹ 合成 ER。
    English: a stress mark's time goes to the sound right after it and its level to the next vowel; ɜɹ, and əɹ when no
    vowel follows, become ER."""
    laid, total = _layout(units, lead, trail)
    segs: list[Seg] = []
    pending_start: int | None = None
    pending_stress = 0
    for u, a, b in laid:
        sym = u.symbol
        if sym in STRESS:
            pending_start = a if pending_start is None else pending_start
            pending_stress = STRESS[sym]
            continue
        start = a if pending_start is None else pending_start
        pending_start = None
        if sym in SPACES:
            segs.append(Seg(" ", sym, start, b))
            pending_stress = 0
        elif sym in PUNCT:
            segs.append(_pause(sym, start, b))
            pending_stress = 0
        elif sym == "ː" and segs and segs[-1].phone not in (" ", "sil"):
            segs[-1].end = b
        else:
            phone = EN_SYMBOLS.get(sym, "?")
            extra: dict = {"stress": None}
            if phone in EN_VOWELS:
                extra["stress"] = pending_stress
                pending_stress = 0
            segs.append(Seg(phone, sym, start, b, u.word, extra))
    # 合并成 ER / merge into ER
    out: list[Seg] = []
    for i, s in enumerate(segs):
        prev = out[-1] if out else None
        if s.symbol == "ɹ" and prev is not None and prev.word == s.word and prev.symbol in ("ɜ", "ə"):
            nxt = segs[i + 1] if i + 1 < len(segs) else None
            vowel_follows = nxt is not None and nxt.word == s.word and nxt.phone in EN_VOWELS
            if prev.symbol == "ɜ" or not vowel_follows:
                prev.phone, prev.symbol, prev.end = "ER", prev.symbol + "ɹ", s.end
                continue
        out.append(s)
    return align(_finish(out, total, lead), total, audible)


def mandarin_segments(units: list[Unit], lead: int, trail: int, audible: list[bool] | None = None) -> list[Seg]:
    """普通话：声调数字的时间并入它前面的音（韵母，或儿化的 r），声调记在这个音节的韵母和儿化上。
    Mandarin: a tone digit's time goes to the sound before it (the final, or the r of erhua) and the tone is recorded
    on the syllable's final and on the erhua."""
    laid, total = _layout(units, lead, trail)
    segs: list[Seg] = []
    for u, a, b in laid:
        sym = u.symbol
        if sym in ZH_TONES:
            tone = int(sym)
            k = len(segs) - 1
            if k >= 0 and segs[k].phone not in (" ", "sil"):
                segs[k].end = b
                while k >= 0 and segs[k].extra.get("part") in ("final", "erhua"):
                    segs[k].extra["tone"] = tone
                    k -= 1
            else:
                segs.append(Seg(" ", sym, a, b))
        elif sym in SPACES:
            segs.append(Seg(" ", sym, a, b))
        elif sym in PUNCT:
            segs.append(_pause(sym, a, b))
        elif sym in ZH_INITIALS:
            segs.append(Seg(ZH_INITIALS[sym], sym, a, b, u.word, {"part": "initial", "tone": None}))
        elif sym in ZH_FINALS:
            segs.append(Seg(ZH_FINALS[sym], sym, a, b, u.word, {"part": "final", "tone": None}))
        elif sym == ZH_ERHUA:
            segs.append(Seg("r", sym, a, b, u.word, {"part": "erhua", "tone": None}))
        else:
            segs.append(Seg("?", sym, a, b, u.word, {"part": "other", "tone": None}))
    return align(_finish(segs, total, lead), total, audible)


def timeline(segs: list[Seg], word_texts: list[str]) -> tuple[list[dict], list[dict]]:
    """时间线的两个输出：音素和词（秒，保留四位小数）。 / The two outputs: phones and words (seconds, four decimals)."""
    t = lambda half: round(half * HALF, 4)  # noqa: E731
    phones = [{"t0": t(s.start), "t1": t(s.end), "phone": s.phone, "symbol": s.symbol, "word": s.word, **s.extra} for s in segs]
    spans: dict[int, list[int]] = {}
    for s in segs:
        if s.word is not None:
            span = spans.setdefault(s.word, [s.start, s.end])
            span[0], span[1] = min(span[0], s.start), max(span[1], s.end)
    # 没有音的词（例如被跳过的）不出现；词的下标重新编号 / words without sounds (skipped ones) are left out; indices are renumbered
    order = sorted(spans)
    renumber = {old: new for new, old in enumerate(order)}
    for p in phones:
        p["word"] = renumber.get(p["word"]) if p["word"] is not None else None
    words = [{"t0": t(spans[i][0]), "t1": t(spans[i][1]), "text": word_texts[i]} for i in order]
    return phones, words
