def build(state: Path, out: Path, log=print) -> dict:
    import numpy as np

    engine = Engine(state)
    engine.start()
    out.mkdir(parents=True, exist_ok=True)
    clips = []
    for lang, sentences in SENTENCES.items():
        for n, (voice, text) in enumerate(sentences, start=1):
            result = engine.synthesize(schema.validate({"text": text, "lang": lang, "voice": voice}), wait_seconds=300)
            name = f"{lang}-{n:02d}.wav"
            data = wav_bytes(result["pcm16"], result["sampleRate"])
            (out / name).write_bytes(data)
            pcm = np.frombuffer(result["pcm16"], dtype="<i2").astype(np.float64) / 32768
            sounds = [p for p in result["phonemes"] if p["phone"] != "sil"]
            diffs = measure.stop_differences(pcm, result["sampleRate"], result["phonemes"], lang)
            clips.append({
                "file": name, "lang": lang, "voice": voice, "speed": 1.0, "text": text,
                "sampleRate": result["sampleRate"], "durationS": result["durationS"], "bytes": len(data), "sha256": hashlib.sha256(data).hexdigest(),
                "model": result["model"], "symbols": result["symbols"], "warnings": result["warnings"],
                "phonemes": result["phonemes"], "words": result["words"],
                "stats": {"phones": len(sounds), "meanPhoneMs": round(1000 * sum(p["t1"] - p["t0"] for p in sounds) / len(sounds), 1),
                          "stopClosureDiffMs": [round(v * 1000, 1) for v in diffs["closure"]], "stopReleaseDiffMs": [round(v * 1000, 1) for v in diffs["release"]]},
            })
            log(f"{name} {result['durationS']:.2f}s {len(sounds)} phones")
    manifest = {
        "_doc": {
            "zh": "语音合成的示范片段：机器合成的声音（24 kHz、单声道、16 位）和它的音素时间线，格式和后端 /api/tts 返回的相同（phonemes、words）。没有后端时界面用这些片段。stats 里的 stopClosureDiffMs / stopReleaseDiffMs 是时间线的粗检：塞音处声音能量骤降 / 骤升的时刻减去时间线上塞音的起点 / 终点（毫秒）。",
            "en": "Speech-synthesis demo clips: machine-generated audio (24 kHz, mono, 16-bit) with its phoneme timeline, in the format the backend's /api/tts returns (phonemes, words). The UI uses these clips when there is no backend. stopClosureDiffMs / stopReleaseDiffMs under `stats` are a rough check on the timeline: the moment the audio's energy falls / rises at a stop minus the start / end of that stop in the timeline (ms).",
        },
        "generatedBy": {"service": "soma-tts", "version": __version__, "command": COMMAND},
        "licence": "machine-generated by Apache-2.0 models (Kokoro-82M v1.0, Kokoro-82M-v1.1-zh); no further restriction added by this project; see LICENSE.txt and ATTRIBUTION.txt",
        "clips": clips,
    }
    (out / "manifest.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    (out / "LICENSE.txt").write_text(LICENSE_TEXT, encoding="utf-8")
    (out / "ATTRIBUTION.txt").write_text(ATTRIBUTION_TEXT.format(command=COMMAND), encoding="utf-8")
    return manifest


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="生成示范片段 / generate the demo clips")
    parser.add_argument("--state", default=None)
    parser.add_argument("--out", required=True)
    args = parser.parse_args(argv)
    manifest = build(config.state_dir(args.state), Path(args.out).resolve())
    for lang in SENTENCES:
        closure = [v / 1000 for c in manifest["clips"] if c["lang"] == lang for v in c["stats"]["stopClosureDiffMs"]]
        release = [v / 1000 for c in manifest["clips"] if c["lang"] == lang for v in c["stats"]["stopReleaseDiffMs"]]
        print(lang, "closure", measure.summary(closure), "release", measure.summary(release))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
