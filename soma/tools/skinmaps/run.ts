// 入口：bun tools/skinmaps/run.ts [male|female] [--no-preview]
// 写出 public/anatomy/<body>/skinmaps.json 与 skinmaps.bin、data/curated/skinmaps/innervation.<body>.json，
// 以及 tools/skinmaps/out/ 下的检验报告和预览图（不入库）。
// Entry point. Writes public/anatomy/<body>/skinmaps.json + skinmaps.bin, the innervation table
// under data/curated/skinmaps/, and the report and previews under tools/skinmaps/out/ (not committed).

import { mkdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import type { BodyId } from '../../src/anatomy/types.ts'
import { CURATED, generate, ROOT } from './generate.ts'
import { writePreviews } from './previews.ts'

const bodyId = (process.argv.includes('female') ? 'female' : 'male') as BodyId
const t0 = performance.now()
const g = await generate(bodyId)
const dir = join(ROOT, 'public/anatomy', bodyId)
writeFileSync(join(dir, 'skinmaps.bin'), g.bin)
writeFileSync(join(dir, 'skinmaps.json'), JSON.stringify(g.skinMaps))
writeFileSync(
  join(CURATED, `innervation.${bodyId}.json`),
  JSON.stringify({
    _doc: {
      zh: '由 tools/skinmaps/run.ts 生成：皮节 → 节段 → 本模型中的脊神经根/神经节部件；皮神经分布区 → 神经部件 → 上级神经链（gapMm 为与上一环节中心线的最小间距，毫米）→ 节段（出处见 cutaneous.json）。未经审校。',
      en: 'Generated by tools/skinmaps/run.ts: dermatome → segments → the spinal root / ganglion parts of this body; cutaneous territory → nerve parts → parent chain (gapMm = smallest gap to the previous link\'s centreline, mm) → segments (sources in cutaneous.json). Unreviewed.',
    },
    body: bodyId,
    skinPart: g.skinMaps.part,
    ...g.tables,
  }, null, 1) + '\n',
)
const out = join(ROOT, 'tools/skinmaps/out')
mkdirSync(out, { recursive: true })
writeFileSync(join(out, `report.${bodyId}.json`), JSON.stringify({ ...g.report, notes: { dermatome: g.dermatome.notes, cutaneous: g.cutaneous.notes } }, null, 1))
if (!process.argv.includes('--no-preview')) writePreviews(g, out, bodyId)

const r = g.report
console.log(`${bodyId}: skin ${r.skinPart} hash ${r.skinHash}, ${r.vertexCount} vertices (${r.outerVertices} outer)`)
console.log(`dermatomes: unassigned ${r.dermatome.unassigned.count}, key points failed ${r.dermatome.keyPointsFailed.length}/${r.dermatome.keyPoints.length}, checks failed ${r.dermatome.checks.filter((c) => !c.ok).length}/${r.dermatome.checks.length}, split regions ${r.dermatome.pieces.length}`)
console.log(`cutaneous: unassigned ${r.cutaneous.unassigned.count}, territories below 50% in textbook segments ${r.cutaneous.composition.filter((c) => c.flagged).map((c) => c.key).join(', ') || 'none'}, split regions ${r.cutaneous.pieces.length}`)
for (const n of [...g.dermatome.notes, ...g.cutaneous.notes]) console.log('note:', n)
console.log(`done in ${((performance.now() - t0) / 1000).toFixed(1)} s`)
