#!/usr/bin/env python3
"""Step 4 of the anchor package: README.md (format) and SANITY.md (numbers) from manifest.json
and sanity.json. Usage: python -I write_reports.py OUT_DIR"""
import json
import os
import sys
from collections import Counter


def table(head, rows):
    out = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def main():
    out = sys.argv[1]
    m = json.load(open(os.path.join(out, "manifest.json")))
    s = json.load(open(os.path.join(out, "sanity.json")))
    items = m["items"]
    vf = [i for i in items if i["source"] == "vhf-ct"]
    hra = [i for i in items if i["source"] == "hra"]

    readme = f"""# soma female anchor set

Female structures to register the male model onto. {len(vf)} `scanned` structures segmented from the
Visible Human Female CT and {len(hra)} `curated` female-specific structures from the Human Reference
Atlas, all in one frame. Generated by `tools/register/run_anchors.sh`; do not edit by hand.

Dataset licence: CC BY-SA 4.0. Required attributions are per item in `manifest.json`
(`attribution`) and per source in `sources`:

- Visible Human Female CT — "{m['sources'][0]['attribution']}".
- {m['sources'][1]['attribution']}.
- Segmentation tools to cite: {m['tools'][0]['name']} and {m['tools'][1]['name']} (`tools[].cite`).

## Files

| File | Content |
|---|---|
| `manifest.json` | frame, sources, fixes, pose (kinematics + re-posing), HRA placement report, one record per item |
| `scanned.bin` | every item as scanned (supine donor, hands on the pelvis) |
| `reposed.bin` | the same items minus `pose == "scanned-only"`, with the upper-limb bones moved to the male's arms-down pose |
| `sanity.json`, `SANITY.md` | size ratios, symmetry, coverage, placement checks |
| `preview/*.png` | quick-look renders |
| `work/` | intermediate volumes and caches (fixed CT, label maps, mesh cache); not part of the package |

## Frame

Metres. +X = patient left, +Y = up, +Z = anterior — the same convention as `public/anatomy/male`.
{m['frame']['origin']}.

`frame.voxel_to_anchor` is the row-major 4x4 from voxel index (i, j, k) of the fixed 480x480x1734
1 mm volume: `X = -0.001 i + {m['frame']['voxel_to_anchor'][3]:.5f}`, `Y = 0.001 k`,
`Z = 0.001 j + {m['frame']['voxel_to_anchor'][11]:.5f}`. k = 2734 - NLM file number.

## Reading a mesh (TypeScript / Bun)

```ts
const manifest = await Bun.file('manifest.json').json()
const bin = await Bun.file('scanned.bin').arrayBuffer()      // or reposed.bin
const item = manifest.items.find((i) => i.id === 'VF_femur_left')
const m = item.mesh.scanned                                   // item.mesh.reposed is null for scanned-only items
const positions = new Float32Array(bin, m.positions.byteOffset, m.positions.count * 3)
const indices = new Uint32Array(bin, m.indices.byteOffset, m.indices.count)
```

Little-endian, positions as xyz float32, indices as uint32 triples, outward counter-clockwise winding.
All byte offsets are multiples of 4.

## Item record

| Field | Meaning |
|---|---|
| `id` | `VF_*` = CT-derived, `HRA_*` = Human Reference Atlas |
| `provenance` | `scanned` or `curated` |
| `segmentation` | tool, task and label(s) the mesh came from (null for HRA) |
| `fma`, `ontology_id` | FMA id where established (one-to-one male match, or HRA crosswalk: FMA or UBERON) |
| `male_parts`, `correspondence` | ids in `public/anatomy/male/anatomy.json`; `one-to-one`, `group` (the item equals the union of the listed parts) or `none` |
| `quality`, `quality_reasons` | `good`, `usable` or `poor`, with the reason |
| `pose` | `both`, or `scanned-only` for soft tissue that is only valid in the scan pose |
| `repose` | row-major 4x4 applied to this item in `reposed.bin` (null = unchanged) |
| `bbox`, `centroid`, `volume_ml`, `triangles` | as scanned; `bbox_reposed` where moved |

## Lumbar vertebrae

{m['lumbar_mapping']['rule']}. {m['lumbar_mapping']['consequence']}.

## Denver hook

Not present in this build. Drop the extracted "Final 3D STL Models" of the University of Denver
Visible Human Female set into `{m['hooks']['denver']['expected_directory']}/`. It would add:
{'; '.join(m['hooks']['denver']['would_add'])}. Import is {m['hooks']['denver']['import_status']}.
"""
    open(os.path.join(out, "README.md"), "w").write(readme)

    # ── SANITY.md ────────────────────────────────────────────────────────────────────────────
    L = ["# Anchor package: sanity report", "", "All numbers are computed by `build_package.py`; nothing here was reviewed by an anatomist.", ""]
