// 语料一侧：对 VIVAE 的疼痛录音逐个做声学分析，只留下每个强度等级的汇总统计量。
// 不输出任何逐文件的数值，也不输出音频。
// The corpus side: analyse each VIVAE pain recording and keep nothing but aggregate statistics per
// intensity level. No per-file value and no audio leaves this module.

import { existsSync, readdirSync, readFileSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { RAINE_LEVELS, VIVAE_LEVELS } from '../../src/voice/control.ts'
import { aggregate, DEFAULT_ANALYSIS, measure, type Aggregate, type Measures } from './analysis.ts'
import { decodeWav } from './wav.ts'

export const ROOT = fileURLToPath(new URL('../..', import.meta.url))
export const VIVAE_DIR = join(ROOT, 'data/raw/voice/vivae-zenodo-4066235/VIVAE/full_set')
export const CALIBRATION_PATH = join(ROOT, 'data/curated/voice/calibration.json')
export const LEVELS = ['low', 'moderate', 'strong', 'peak'] as const
export type Level = (typeof LEVELS)[number]
export const STAT_KEYS = ['durationS', 'levelDb', 'peakDb', 'voicedShare', 'f0MeanHz', 'f0MedianHz', 'f0P5Hz', 'f0P95Hz', 'f0RangeSt', 'hnrDb', 'centroidHz', 'nonlinearShare', 'subShare', 'chaosShare'] as const satisfies readonly (keyof Measures)[]
export type StatKey = (typeof STAT_KEYS)[number]
export type LevelStats = Record<StatKey, Aggregate>

export interface Calibration {
  _doc: { zh: string; en: string }
  sources: unknown[]
  method: { zh: string; en: string }
  analysisOptions: typeof DEFAULT_ANALYSIS
  intensityMapping: unknown
  vivae: { subset: { zh: string; en: string }; levels: Record<Level, { intensity: number; n: number; speakers: number; measures: LevelStats }> }
  raine2019: unknown
}

export const corpusPresent = () => existsSync(VIVAE_DIR)

export function summarise(ms: Measures[]): LevelStats {
  return Object.fromEntries(STAT_KEYS.map((k) => [k, aggregate(ms.map((m) => m[k]))])) as LevelStats
}

export function analyseCorpus(dir = VIVAE_DIR): Calibration['vivae']['levels'] {
  const by: Record<Level, Measures[]> = { low: [], moderate: [], strong: [], peak: [] }
  const speakers: Record<Level, Set<string>> = { low: new Set(), moderate: new Set(), strong: new Set(), peak: new Set() }
  for (const name of readdirSync(dir).sort()) {
    const m = /^(S\d+)_pain_(low|moderate|strong|peak)_\d+\.wav$/.exec(name)
    if (!m) continue
    const wav = decodeWav(readFileSync(join(dir, name)))
    by[m[2] as Level].push(measure(wav.samples, wav.sampleRate))
    speakers[m[2] as Level].add(m[1]!)
  }
  return Object.fromEntries(LEVELS.map((lv) => [lv, { intensity: VIVAE_LEVELS[lv], n: by[lv].length, speakers: speakers[lv].size, measures: summarise(by[lv]) }])) as Calibration['vivae']['levels']
}

